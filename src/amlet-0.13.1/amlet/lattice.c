/**
 * Read the lattices dimension.
 *
 * @param f is the file containing the lattices parameters.
 *
 * @return the dimension of the lattice to consider in the file, starting
 *   from the line below the current one.
 */
int amlet_read_lattices_dimension(FILE *f)
{
  char *line, *start, *t;
  int s = 0;

  line = c_file_get_line(f);
  start = line;
  t = _mallocs(strlen(line), char);

  while (sscanf(line, "%s", t) == 1) {
    s++;
    line += strlen(t);
    line = c_string_skip_spaces(line);
  }

  if (s == 1)
    sscanf(t, "%d", &s);
  else
    s -= 2;

  free(start);
  free(t);

  return s;
}

/**
 * Read lattices parameters.
 * The function does not check that the file is properly formed. Use it at
 * your own risk!
 *
 * @param f is the file containing the lattices parameters.
 * @param s is the lattices dimension.
 * @param lattices is a pointer to an unallocated integer array on input,
 *   and to the lattices description on output.
 * @param nlattices is a pointer to an integer containing on output the
 *   number of parameters sets (each one defined for a certain number of
 *   points).
 *
 * @return the number of defined lattices.
 */
int amlet_read_lattices(FILE *f, int s, int **lattices, int *nlattices)
{
  int i, j, n, p, pos=0;
  int cont = 1;
  int max_size;

  char *line;

  max_size = 10*(s+1);
  *lattices = _mallocs(max_size, int);

  j = 0;

  while (cont > 0) {
    line = c_file_get_line(f);
    if (line) {
      c_file_line_cut_comments(line);
      /* Read the number of points. */
      cont = sscanf(line, "%d%n", &n, &p);
      if (cont > 0) {
	pos = p;
	(*lattices)[j++] = n;
	/* Read the Lattice parameters. */
	for (i = 0; i < s && cont; i++) {
	  cont = sscanf(line+pos, "%d%n", &((*lattices)[j++]), &p);
	  pos += p;
	}
      }
      if (j == max_size) {
	max_size *= 2;
	*lattices = _reallocs(*lattices, max_size, int);
      }
      free(line);
    }
    else
      cont = 0;
  }

  if (j)
    *lattices = _reallocs(*lattices, j, int);
  else {
    free(*lattices);
    *lattices = NULL;
  }

  *nlattices = j/(s+1);

  return *nlattices;
}
